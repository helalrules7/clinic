#!/usr/bin/env php
<?php
/**
 * backup-run.php — Backup engine (CLI, runs in the background).
 *
 * Usage:  php bin/backup-run.php <jobId> <type> <scope> <triggerUserId>
 *   type:  database | database_uploads | system
 *   scope (database only): main | drugs | both    (ignored otherwise)
 *
 * Why a CLI runner (not the web request):
 *   - The full-system archive is ~1GB → would time out a web request.
 *   - mysqldump CLI fails for the app DB user on prod, so the SQL dump is
 *     done in PURE PHP via PDO (works in CLI too).
 *   - The web user can't read root's crontab → the cron list is a maintained
 *     snapshot written here.
 *
 * Writes progress to  backups/.status/<jobId>.json  (polled by the UI) and
 * notifies ALL doctors/admins when the backup is ready.
 */

define('ROOT', realpath(__DIR__ . '/..'));           // site/ (= public_html on prod)
require_once ROOT . '/app/Config/Database.php';
require_once ROOT . '/app/Controllers/NotificationController.php';

use App\Config\Database;
use App\Controllers\NotificationController;

// Loads .env into $_ENV (DB_HOST=db, etc.) — must run before any pdoFor() call,
// otherwise the dump connection falls back to a UNIX socket and fails.
Database::getInstance();

$jobId   = preg_replace('/[^a-zA-Z0-9_\-]/', '', $argv[1] ?? '');
$type    = $argv[2] ?? '';
$scope   = $argv[3] ?? 'both';
$byUser  = (int)($argv[4] ?? 0);

if ($jobId === '' || !in_array($type, ['database', 'database_uploads', 'system'], true)) {
    fwrite(STDERR, "bad args\n"); exit(2);
}

// Backups live OUTSIDE the docroot (panel `private/` dir — in open_basedir,
// writable, not nginx-served). Fall back to <app>/backups for local dev.
$private = dirname(ROOT) . '/private';
$BACKDIR = (is_dir($private) && is_writable($private)) ? $private . '/backups' : ROOT . '/backups';
$STATDIR = $BACKDIR . '/.status';
@mkdir($STATDIR, 0775, true);
$statusFile = "$STATDIR/$jobId.json";

$state = [
    'job' => $jobId, 'type' => $type, 'scope' => $scope,
    'status' => 'running', 'phase' => 'starting', 'pct' => 0,
    'file' => null, 'size' => 0, 'error' => null,
    'started' => date('c'), 'finished' => null,
];
function put_status() { global $statusFile, $state; @file_put_contents($statusFile, json_encode($state)); }
function phase($p, $pct) { global $state; $state['phase'] = $p; $state['pct'] = $pct; put_status(); }
put_status();

// ── dedicated PDO connections (unbuffered, so big tables don't blow memory) ──
function pdoFor($which) {
    $host = $_ENV['DB_HOST'] ?? 'localhost';
    if ($which === 'drugs') {
        // Defaults MUST match DoctorController::getDrugsDatabaseConnection() — the prod
        // .env has no DRUGS_DB_* keys, and the drugs DB user differs from the main one.
        $db = $_ENV['DRUGS_DB_NAME'] ?? 'hclinic_drugs';
        $u  = $_ENV['DRUGS_DB_USER'] ?? 'hclinic_drugs';
        $p  = $_ENV['DRUGS_DB_PASS'] ?? 'Carmen@1230';
    } else {
        $db = $_ENV['DB_NAME'] ?? 'hclinic_roaya';
        $u  = $_ENV['DB_USER'] ?? 'hclinic_roaya';
        $p  = $_ENV['DB_PASS'] ?? 'Carmen@1230';
    }
    $pdo = new PDO("mysql:host=$host;dbname=$db;charset=utf8mb4", $u, $p, [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::MYSQL_ATTR_USE_BUFFERED_QUERY => false,
    ]);
    return [$pdo, $db];
}

// ── pure-PHP SQL dump (mysqldump-compatible enough for a full restore) ──
function dumpDatabase($pdo, $dbName, $outPath) {
    $fh = fopen($outPath, 'w');
    if (!$fh) throw new Exception("cannot write $outPath");
    fwrite($fh, "-- Backup of `$dbName` — " . date('c') . "\n");
    fwrite($fh, "-- Generated by Roaya backup engine (PHP/PDO)\n");
    fwrite($fh, "SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS=0;\nSET SQL_MODE='NO_AUTO_VALUE_ON_ZERO';\n\n");

    $tables = $pdo->query("SHOW FULL TABLES")->fetchAll(PDO::FETCH_NUM);
    foreach ($tables as $row) {
        $tbl  = $row[0];
        $kind = $row[1] ?? 'BASE TABLE';
        $cr = $pdo->query("SHOW CREATE TABLE `$tbl`")->fetch(PDO::FETCH_ASSOC);
        if ($kind === 'VIEW') {
            fwrite($fh, "DROP VIEW IF EXISTS `$tbl`;\n" . ($cr['Create View'] ?? '') . ";\n\n");
            continue;
        }
        fwrite($fh, "DROP TABLE IF EXISTS `$tbl`;\n" . ($cr['Create Table'] ?? '') . ";\n\n");

        $sel = $pdo->query("SELECT * FROM `$tbl`");
        $cols = null;
        while ($r = $sel->fetch(PDO::FETCH_ASSOC)) {
            if ($cols === null) $cols = '`' . implode('`,`', array_keys($r)) . '`';
            $vals = [];
            foreach ($r as $v) {
                $vals[] = ($v === null) ? 'NULL' : $pdo->quote((string)$v);
            }
            fwrite($fh, "INSERT INTO `$tbl` ($cols) VALUES (" . implode(',', $vals) . ");\n");
        }
        $sel->closeCursor();
        fwrite($fh, "\n");
    }
    fwrite($fh, "SET FOREIGN_KEY_CHECKS=1;\n");
    fclose($fh);
}

function sh($cmd) { $o = []; $rc = 0; exec($cmd . ' 2>&1', $o, $rc); return [$rc, implode("\n", $o)]; }

$ts = date('Ymd-His');
$work = "$BACKDIR/.work_$jobId";
@mkdir($work, 0775, true);
@mkdir("$work/database", 0775, true);

try {
    // ── 1) database dump(s) ──
    if ($type === 'database') {
        $want = ($scope === 'main' || $scope === 'drugs') ? [$scope] : ['main', 'drugs'];
    } else {
        $want = ['main', 'drugs']; // uploads + system always include both DBs
    }
    $p = 5;
    foreach ($want as $w) {
        phase("dumping $w database", $p);
        [$pdo, $db] = pdoFor($w);
        dumpDatabase($pdo, $db, "$work/database/$w-$db.sql");
        $pdo = null;
        $p += ($type === 'database') ? (60 / count($want)) : 25;
    }

    $finalName = null;
    if ($type === 'database') {
        phase('compressing', 80);
        $finalName = "database_{$scope}_{$ts}.tar.gz";
        [$rc, $out] = sh('tar czf ' . escapeshellarg("$BACKDIR/$finalName.part")
            . ' -C ' . escapeshellarg("$work/database") . ' .');
        if ($rc !== 0) throw new Exception("tar failed: $out");
        rename("$BACKDIR/$finalName.part", "$BACKDIR/$finalName");

    } elseif ($type === 'database_uploads') {
        phase('archiving database + uploads', 55);
        $finalName = "database_uploads_{$ts}.tar.gz";
        $dirs = array_values(array_filter(
            ['app/storage/uploads', 'public/uploads', 'uploads'],
            function ($d) { return is_dir(ROOT . '/' . $d); }
        ));
        $cmd = 'tar czf ' . escapeshellarg("$BACKDIR/$finalName.part")
             . ' -C ' . escapeshellarg($work) . ' database'
             . ' -C ' . escapeshellarg(ROOT) . ' ' . implode(' ', array_map('escapeshellarg', $dirs));
        [$rc, $out] = sh($cmd);
        if ($rc !== 0 && !is_file("$BACKDIR/$finalName.part")) throw new Exception("tar failed: $out");
        rename("$BACKDIR/$finalName.part", "$BACKDIR/$finalName");

    } else { // system
        phase('writing cron snapshot', 40);
        file_put_contents("$work/cron-jobs.txt", cronSnapshot());
        phase('archiving full system (this can take a while)', 50);
        $finalName = "system_{$ts}.tar.gz";
        $parent = dirname(ROOT);
        $base   = basename(ROOT);
        // public_html/ contents + database/ + cron snapshot; exclude the backups
        // dir itself (recursion) and .git.
        $cmd = 'tar czf ' . escapeshellarg("$BACKDIR/$finalName.part")
             . ' --exclude=' . escapeshellarg("$base/backups")
             . ' --exclude=' . escapeshellarg("$base/.git")
             . ' -C ' . escapeshellarg($work) . ' database cron-jobs.txt'
             . ' -C ' . escapeshellarg($parent) . ' ' . escapeshellarg($base);
        [$rc, $out] = sh($cmd);
        // tar returns 1 on "file changed as we read it" — tolerate if the archive exists.
        if (!is_file("$BACKDIR/$finalName.part")) throw new Exception("tar failed: $out");
        rename("$BACKDIR/$finalName.part", "$BACKDIR/$finalName");
    }

    $state['status']  = 'done';
    $state['phase']   = 'ready';
    $state['pct']     = 100;
    $state['file']    = $finalName;
    $state['size']    = is_file("$BACKDIR/$finalName") ? filesize("$BACKDIR/$finalName") : 0;
    $state['finished'] = date('c');
    put_status();

    notifyDoctors($type, $finalName, $state['size'], $byUser);

} catch (Throwable $e) {
    $state['status'] = 'error';
    $state['phase']  = 'failed';
    $state['error']  = $e->getMessage();
    $state['finished'] = date('c');
    put_status();
    fwrite(STDERR, $e->getMessage() . "\n");
} finally {
    // best-effort cleanup of the working dir
    if (is_dir($work)) { sh('rm -rf ' . escapeshellarg($work)); }
}

function cronSnapshot() {
    // The web/cli app user can't read root's crontab; this is the maintained
    // snapshot of the app's scheduled jobs (keep in sync with the server cron).
    $php = '/usr/bin/php';
    $base = ROOT;
    return "# Roaya / HClinic — scheduled jobs snapshot ( " . date('c') . " )\n"
        . "# NOTE: documented snapshot — the live root crontab must be confirmed on the server.\n\n"
        . "*/5 * * * * $php $base/bin/cron/todo-reminders.php >> /var/log/roaya-todo-cron.log 2>&1\n"
        . "17 3 * * * $php $base/bin/cron/purge-orphan-attachments.php >> /var/log/roaya-chat-purge.log 2>&1\n";
}

function notifyDoctors($type, $file, $size, $byUser) {
    try {
        $pdo = Database::getInstance()->getConnection();
        $label = [
            'database' => 'Database backup',
            'database_uploads' => 'Database + uploads backup',
            'system' => 'Full system backup',
        ][$type] ?? 'Backup';
        $mb = $size ? round($size / 1048576, 1) . ' MB' : '';
        $msg = "$label is ready to download" . ($mb ? " ($mb)" : '') . ".";
        $ids = $pdo->query("SELECT id FROM users WHERE role IN ('doctor','admin')")->fetchAll(PDO::FETCH_COLUMN);
        foreach ($ids as $uid) {
            NotificationController::create((int)$uid, 'system', 'Backup ready', $msg, 'backup', null);
        }
    } catch (Throwable $e) { /* non-fatal */ }
}
